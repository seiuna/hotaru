    private static void testErrorMapping() {
        section("error envelope mapping");

        McAuthException notPremium = McAuthException.fromHttp(401, """
                {"error":{"code":"NOT_A_PREMIUM_SESSION",
                          "message":"Mojang did not confirm an active premium session for this player",
                          "retryable":false}}""");
        check("401 NOT_A_PREMIUM_SESSION code", "NOT_A_PREMIUM_SESSION".equals(notPremium.errorCode()),
                "got " + notPremium.errorCode());
        check("401 NOT_A_PREMIUM_SESSION not retryable", !notPremium.retryable(), "was retryable");
        check("401 status preserved", notPremium.httpStatus() == 401, "got " + notPremium.httpStatus());

        McAuthException consumed = McAuthException.fromHttp(409, """
                {"error":{"code":"CHALLENGE_CONSUMED","message":"Challenge was already consumed","retryable":false}}""");
        check("409 CHALLENGE_CONSUMED", "CHALLENGE_CONSUMED".equals(consumed.errorCode()), "got " + consumed.errorCode());

        McAuthException mojang = McAuthException.fromHttp(503, """
                {"error":{"code":"MOJANG_UNAVAILABLE","message":"upstream down","retryable":true}}""");
        check("503 MOJANG_UNAVAILABLE retryable", mojang.retryable(), "was not retryable");

        McAuthException limited = McAuthException.fromHttp(429, """
                {"error":{"code":"RATE_LIMITED","message":"too many attempts","retryable":true,
                          "details":{"retryAfterSeconds":30}}}""");
        check("429 RATE_LIMITED details parsed",
                limited.details() instanceof Map<?, ?> details && Long.valueOf(30).equals(details.get("retryAfterSeconds")),
                "details=" + limited.details());

        McAuthException gateway = McAuthException.fromHttp(502, "<html>bad gateway</html>");
        check("non-JSON 5xx falls back to INTERNAL and stays retryable",
                "INTERNAL".equals(gateway.errorCode()) && gateway.retryable(),
                "got " + gateway.errorCode() + " retryable=" + gateway.retryable());

        McAuthException transport = McAuthException.transport("connect timed out", null);
        check("transport failures are retryable with status 0",
                transport.retryable() && transport.httpStatus() == 0
                        && "TRANSPORT_ERROR".equals(transport.errorCode()),
                "got " + transport);
    }

    /* ------------------------------------------------------------------ */
    /* 7. Offline validation                                               */
    /* ------------------------------------------------------------------ */

    private static void testOfflineValidation() {
        section("offline argument validation (no network)");
        McAuthClient client = McAuthClient.builder("http://127.0.0.1:9/").build();
        check("baseUrl trailing slash is normalised",
                "http://127.0.0.1:9".equals(client.baseUri().toString()), "got " + client.baseUri());

        McAuthException badUsername = null;
        try {
            client.requestChallenge("ab");
        } catch (McAuthException e) {
            badUsername = e;
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
        check("invalid username fails locally", badUsername != null
                        && "INVALID_REQUEST".equals(badUsername.errorCode())
                        && badUsername.httpStatus() == 0
                        && !badUsername.retryable(),
                "got " + badUsername);

        boolean rejectedScheme = false;
        try {
            McAuthClient.builder("ftp://example.com").build();
        } catch (IllegalArgumentException e) {
            rejectedScheme = true;
        }
        check("non-http baseUrl is rejected", rejectedScheme, "ftp:// was accepted");

        boolean rejectedZeroTimeout = false;
        try {
            McAuthClient.builder("https://auth.example.com").requestTimeout(java.time.Duration.ZERO).build();
        } catch (IllegalArgumentException e) {
            rejectedZeroTimeout = true;
        }
        check("zero timeout is rejected", rejectedZeroTimeout, "Duration.ZERO was accepted");
    }

    /* ------------------------------------------------------------------ */
    /* Helpers                                                             */
    /* ------------------------------------------------------------------ */

    /**
     * Deliberately naive second implementation of the signed 160-bit hex rendering: manual
     * two's-complement negation on the byte array, manual hex digits. Used to cross-check
     * {@link MinecraftServerHash#toSignedHex(byte[])}.
     */
    private static String referenceSignedHex(byte[] digest) {
        boolean negative = (digest[0] & 0x80) != 0;
        byte[] magnitude;
        if (negative) {
            magnitude = new byte[digest.length];
            int carry = 1;
            for (int i = digest.length - 1; i >= 0; i--) {
                int value = (~digest[i] & 0xFF) + carry;
                magnitude[i] = (byte) value;
                carry = value >> 8;
            }
        } else {
            magnitude = digest.clone();
        }
        int start = 0;
        while (start < magnitude.length - 1 && magnitude[start] == 0) start++;
        StringBuilder hex = new StringBuilder(magnitude.length * 2);
        for (int i = start; i < magnitude.length; i++) {
            hex.append(Character.forDigit((magnitude[i] >> 4) & 0x0F, 16));
            hex.append(Character.forDigit(magnitude[i] & 0x0F, 16));
        }
        while (hex.length() > 1 && hex.charAt(0) == '0') hex.deleteCharAt(0);
        return negative ? "-" + hex : hex.toString();
    }

    private static byte[] concat(byte[] first, byte[] second, byte[] third) {
        byte[] out = new byte[first.length + second.length + third.length];
        System.arraycopy(first, 0, out, 0, first.length);
        System.arraycopy(second, 0, out, first.length, second.length);
        System.arraycopy(third, 0, out, first.length + second.length, third.length);
        return out;
    }

    private static String randomAscii(Random random, int length) {
        StringBuilder out = new StringBuilder(length);
        for (int i = 0; i < length; i++) {
            out.append((char) (0x21 + random.nextInt(0x7E - 0x21 + 1)));
        }
        return out.toString();
    }

    private static void section(String title) {
        System.out.println();
        System.out.println("-- " + title);
    }

    private static void check(String name, boolean condition, String failureDetail) {
        if (condition) {
            passed++;
            System.out.println("PASS  " + name);
        } else {
            failed++;
            System.out.println("FAIL  " + name + " - " + failureDetail);
        }
    }
